// Refresh with: node scripts/generate-country-profiles.mjs YYYY-MM-DD
import { readFileSync, writeFileSync } from 'node:fs'
import { format, resolveConfig } from 'prettier'
import countries from 'country-list/data.json' with { type: 'json' }
import currencies from 'cldr-core/supplemental/currencyData.json' with { type: 'json' }
import subtags from 'cldr-core/supplemental/likelySubtags.json' with { type: 'json' }

const date = process.argv[2]
if (!/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) throw Error('Supply YYYY-MM-DD')
const { currencyData, version } = currencies.supplemental
const profiles = {}
for (const { code } of countries) {
  const tender = currencyData.region[code].flatMap((entry) => {
    const [[currency, { _from, _to, _tender }]] = Object.entries(entry)
    return _tender !== 'false' &&
      (!_from || _from <= date) &&
      (!_to || _to >= date)
      ? [currency]
      : []
  })
  // Retain the plan's region (even when CLDR's likely language is English)
  // and the existing es-PY formatting rather than switching Paraguay to gn.
  const likely = subtags.supplemental.likelySubtags[`und-${code}`] ?? 'en'
  const language = code === 'PY' ? 'es' : new Intl.Locale(likely).language
  profiles[code] = [`${language}-${code}`, ...tender]
}
const path = 'src/lib/country-data.ts'
writeFileSync(
  'public/country-data-licenses.txt',
  ['cldr-core', 'country-list']
    .map((name) =>
      readFileSync(new URL(import.meta.resolve(`${name}/LICENSE`)), 'utf8'),
    )
    .join('\n\n'),
)
writeFileSync(
  path,
  await format(
    `// Generated by scripts/generate-country-profiles.mjs from Unicode CLDR ${version._cldrVersion} as of ${date}. See /country-data-licenses.txt.\nexport const countryData = ${JSON.stringify(profiles)} as const\n`,
    { ...(await resolveConfig(path)), filepath: path },
  ),
)
